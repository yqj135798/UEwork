import unreal


def log_value(label, value):
    unreal.log("[RetargetInspect] {0}: {1}".format(label, value))


def main():
    log_value("IKRigController", [name for name in dir(unreal.IKRigController) if not name.startswith("_")])
    log_value("IKRetargeterController", [name for name in dir(unreal.IKRetargeterController) if not name.startswith("_")])
    log_value("IKRetargetBatchOperation", [name for name in dir(unreal.IKRetargetBatchOperation) if not name.startswith("_")])
    log_value("BatchInput", [name for name in dir(unreal.IKRetargetBatchOperationInputs) if not name.startswith("_")])
    log_value("RetargetEnums", [name for name in dir(unreal) if "Retarget" in name or "AutoMap" in name])
    log_value("RigFactories", [name for name in dir(unreal) if "Rig" in name and "Factory" in name])
    log_value("AutoGenerateDoc", unreal.IKRigController.apply_auto_generated_retarget_definition.__doc__)
    log_value("SetRigMeshDoc", unreal.IKRigController.set_skeletal_mesh.__doc__)
    log_value("SetIKRigDoc", unreal.IKRetargeterController.set_ik_rig.__doc__)
    log_value("BatchDoc", unreal.IKRetargetBatchOperation.run_batch_retarget.__doc__)

    source_mesh = unreal.load_asset("/Game/Characters/Mannequins/Anims/throw/X_Bot_Throw")
    target_mesh = unreal.load_asset("/Game/Characters/Mannequins/Meshes/SKM_Manny_Simple")
    source_rig = unreal.load_asset("/Game/Characters/Mannequins/Anims/throw/IKR_XBot")
    log_value("SourceMesh", source_mesh)
    log_value("TargetMesh", target_mesh)
    log_value("SourceRig", source_rig)

    if source_mesh:
        log_value("SourceMeshMethods", [name for name in dir(source_mesh) if "bone" in name.lower() or "skeleton" in name.lower()])
    if target_mesh:
        log_value("TargetMeshMethods", [name for name in dir(target_mesh) if "bone" in name.lower() or "skeleton" in name.lower()])
    if source_rig:
        controller = unreal.IKRigController.get_controller(source_rig)
        log_value("SourceRigMesh", controller.get_skeletal_mesh())
        log_value("SourceRigChains", controller.get_retarget_chains())


if __name__ == "__main__":
    main()
